/*
  BASE_PATH — базовый путь всех запросов к API (/api/...).

  Зачем нужен: без префикса фронт и бэкенд не «договорятся», какие запросы чьи.
  Пояснение: страница отдаётся с одного адреса, а с ней уходят и запросы за данными,
  и за скриптами, и за картинками. Если все пути смешать в одну кучу, будет непонятно,
  что проксировать. Префикс — это ярлык, по которому nginx отличает запрос к API
  от всего остального (SPA, статика).

  Почему без него никак:
  1. Nginx не узнает запрос к API и отдаст вместо данных index.html
     (типичная ошибка: сервер возвращает HTML вместо JSON).
  2. NestJS не узнает свой роут: у него глобальный префикс 'api',
     и путь /auth/login без /api для него просто не существует (404).
  3. Невозможно локально работать через Vite-прокси — проксировать нечего,
     прокси правило завязано на путь.

  Как работает вся цепочка:
  1. Фронт: берёт BASE_PATH = '/api' → делает запрос на /api/auth/login.
  2. Nginx: видит путь /api/... → по правилу location ~ ^/(api|content)/
     отправляет запрос на бэкенд (backend:3000).
  3. Бэкенд (NestJS): у него app.setGlobalPrefix('api') → путь совпал,
     запрос доходит до контроллера.

  Все три места должны совпасть: BASE_PATH здесь, setGlobalPrefix в NestJS
  и location-правило в nginx. Разошлось хоть в одном — всё перестанет работать.
*/
export const BASE_PATH = '/api';

/*
  CONTENT_PATH — базовый путь к статическим файлам (картинки, видео, вложения).

  Зачем нужен: файлы и данные — это два разных вида трафика, их лучше не смешивать.
  API возвращает лёгкий JSON быстро, а файлы — тяжёлые и отдаются часто.
  Если пускать всё через /api, Node.js будет занят отдачей файлов,
  пока реальные запросы к API ждут своей очереди.

  Почему без него никак:
  1. Нельзя кэшировать: у API-ответов нет кэша (данные меняются),
     а у файлов — есть. Разные пути → разные правила кэширования в nginx.
  2. Бэкенд вернёт ссылку вида CONTENT_PATH + '/files/' + fileCode —
     фронту не важно, где физически лежит файл: он собирает URL из константы.
     Перенесли файлы на CDN или другой домен — меняем одну строку, а не весь код.
  3. Nginx не поймёт, что /files/photo-001.png нужно отдавать с диска
     напрямую (быстро, без Node.js), а не проксировать на бэкенд.

  В проде: nginx видит /content/... → отдаёт файл из папки на сервере.
  Локально: Vite-прокси перекидывает /content/... на бэкенд.

  Пока не используется — префикс на будущее.
*/
